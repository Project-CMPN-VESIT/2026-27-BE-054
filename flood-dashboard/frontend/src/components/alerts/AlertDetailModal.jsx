import { useEffect, useMemo } from 'react';
import { useNavigate } from 'react-router-dom';
import useFloodStore from '../../store/floodStore';
import useAlertDetail from '../../hooks/useAlertDetail';
import { formatINR, formatIndian } from '../../utils/formatters';
import { Droplets, Brain, ClipboardList, X } from 'lucide-react';
import AlertMiniMap from './AlertMiniMap';
import PredictionExplanation from './PredictionExplanation';
import WaterInfraTable from './WaterInfraTable';
import ResourceRequirementTable from './ResourceRequirementTable';

function downloadHtmlReport(detail) {
  const district = detail?.district || 'District';
  const date = new Date().toISOString().slice(0, 10);
  const filename = `DRMS_Alert_${district.replace(/\s+/g, '_')}_${date}.html`;
  const html = `<!doctype html><html><head><meta charset="utf-8"><title>DRMS Alert Report</title>
  <style>body{font-family:Arial,sans-serif;padding:24px;color:#111827}h1{font-size:24px}h2{font-size:18px;margin-top:24px}
  .box{border:1px solid #e5e7eb;border-radius:8px;padding:12px;margin-top:12px}table{width:100%;border-collapse:collapse}
  th,td{border:1px solid #e5e7eb;padding:8px;text-align:left}th{background:#f9fafb}</style></head><body>
  <h1>FLOOD ALERT REPORT — ${detail.district}, ${detail.state}</h1>
  <div>Generated: ${new Date().toLocaleString('en-IN', { timeZone: 'Asia/Kolkata' })} IST</div>
  <div class="box"><strong>Alert Level:</strong> ${detail.alert?.level} <br/><strong>Severity:</strong> ${detail.alert?.severity_score}/10
  <br/><strong>Flood Probability:</strong> ${detail.alert?.flood_probability}%</div>
  <h2>Recommended Actions</h2>
  <ol>${(detail.recommended_actions || []).map((a) => `<li>${a}</li>`).join('')}</ol>
  <div style="margin-top:20px;font-size:12px;color:#64748b">Generated by DRMS</div>
  </body></html>`;
  const blob = new Blob([html], { type: 'text/html;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  link.click();
  URL.revokeObjectURL(url);
}

export default function AlertDetailModal({ state, district, onClose }) {
  const navigate = useNavigate();
  const { geojsonData } = useFloodStore();
  const { data, loading, error, retry } = useAlertDetail(state, district);

  useEffect(() => {
    document.body.style.overflow = 'hidden';
    const onEsc = (e) => {
      if (e.key === 'Escape') onClose();
    };
    window.addEventListener('keydown', onEsc);
    return () => {
      window.removeEventListener('keydown', onEsc);
      document.body.style.overflow = 'unset';
    };
  }, [onClose]);

  const generatedAt = useMemo(
    () => new Date().toLocaleString('en-IN', { timeZone: 'Asia/Kolkata', dateStyle: 'full', timeStyle: 'short' }),
    [],
  );
  const headerColors = {
    CRITICAL: { bg: '#7f1d1d', accent: '#ef4444' },
    HIGH: { bg: '#7c2d12', accent: '#f97316' },
    MEDIUM: { bg: '#713f12', accent: '#eab308' },
    LOW: { bg: '#14532d', accent: '#22c55e' },
  };

  const dispatchNow = () => {
    if (!data) return;
    const q = new URLSearchParams({
      district: data.district,
      lat: String(data.latitude || ''),
      lon: String(data.longitude || ''),
      state: String(data.state || ''),
    });
    onClose();
    navigate(`/routing?${q.toString()}`);
  };

  return (
    <div className="alert-detail-overlay" onClick={(e) => e.target === e.currentTarget && onClose()}>
      <div className="alert-detail-content alert-detail-print">
        {loading && <div className="text-sm text-text-muted">Loading alert detail...</div>}
        {error && (
          <div className="p-4 border border-red-200 rounded-lg bg-red-50 text-sm m-4">
            <div>{error}</div>
            <button className="btn-primary mt-3 text-xs" onClick={retry}>Retry</button>
          </div>
        )}
        {!loading && !error && data && (
          <div>
            <div className="px-6 py-5 text-white" style={{ background: '#1a3c5e' }}>
              <div className="flex items-start justify-between gap-3">
                <div>
                  <div className="flex items-center gap-2 mb-2">
                    <button onClick={onClose} className="text-sm font-semibold text-white/90 hover:text-white">← BACK</button>
                    <span
                      className="px-2 py-1 rounded-full text-[11px] font-bold"
                      style={{ background: headerColors[data.alert?.level]?.accent || '#22c55e', color: '#fff' }}
                    >
                      {data.alert?.level}
                    </span>
                    <span className="font-semibold">FLOOD ALERT REPORT</span>
                  </div>
                  <h2 className="text-xl font-bold">{data.district}, {data.state}</h2>
                  <div className="text-xs text-white/80">Generated: {generatedAt} IST • LIVE</div>
                </div>
                <div className="flex items-center gap-2">
                  <button className="btn-print" onClick={() => window.print()}>🖨 PRINT</button>
                  <button className="btn-print !px-3" onClick={onClose}><X size={16} /></button>
                </div>
              </div>
            </div>

            <section className="alert-section">
              <div className="grid grid-cols-1 lg:grid-cols-[55%_45%] gap-4">
                <AlertMiniMap
                  geojson={geojsonData}
                  districtName={data.district}
                  lat={data.latitude}
                  lon={data.longitude}
                  severityScore={data.alert?.severity_score}
                  waterFeatures={data.water_infrastructure?.features}
                />
                <div>
                  <div className="grid grid-cols-2 gap-3">
                    <div className="stat-box">
                      <div className="stat-box-label">Alert Level</div>
                      <div className="stat-box-value">{data.alert?.level}</div>
                    </div>
                    <div className="stat-box">
                      <div className="stat-box-label">Severity Score</div>
                      <div className="stat-box-value">{data.alert?.severity_score?.toFixed?.(1)} / 10</div>
                      <div className="severity-bar">
                        <div
                          className="severity-bar-fill"
                          style={{
                            width: `${Math.min(100, ((data.alert?.severity_score || 0) / 10) * 100)}%`,
                            background:
                              (data.alert?.severity_score || 0) > 7
                                ? '#ef4444'
                                : (data.alert?.severity_score || 0) > 5
                                  ? '#f97316'
                                  : (data.alert?.severity_score || 0) > 3
                                    ? '#eab308'
                                    : '#22c55e',
                          }}
                        />
                      </div>
                    </div>
                    <div className="stat-box">
                      <div className="stat-box-label">Flood Probability</div>
                      <div className="stat-box-value">{data.alert?.flood_probability}%</div>
                    </div>
                    <div className="stat-box">
                      <div className="stat-box-label">Risk Level</div>
                      <div className="stat-box-value">{data.prediction?.severity_class || data.alert?.level}</div>
                    </div>
                  </div>
                  <div className="mt-4 rounded-lg border border-slate-200 p-4 bg-white">
                    <div className="text-xs font-bold tracking-wide text-slate-500 uppercase mb-2">Population Impact</div>
                    <div className="text-sm space-y-1 text-slate-700">
                      <div>👥 Total Pop: <strong>{formatIndian(data.historical?.population)}</strong></div>
                      <div>⚠️ Potentially Affected (Modeled): <strong>{formatIndian(Math.min(data.historical?.impact_population || 0, data.historical?.population || 0))}</strong></div>
                      <div>☠️ Deaths: <strong>{data.historical?.total_deaths || 0}</strong></div>
                      <div>⏱️ Avg Duration: <strong>{Number(data.historical?.avg_duration_days || 0).toFixed(1)} days</strong></div>
                    </div>
                  </div>
                </div>
              </div>
            </section>

            <section className="alert-section">
              <h3 className="section-title"><Brain size={16} /> WHY WE PREDICTED THIS ALERT</h3>
              <PredictionExplanation factors={data.prediction_explanation} />
            </section>

            <section className="alert-section">
              <h3 className="section-title"><Droplets size={16} /> WATER INFRASTRUCTURE AT RISK</h3>
              <WaterInfraTable
                data={data.water_infrastructure}
                districtName={data.district}
                lat={data.latitude}
                lon={data.longitude}
                loading={loading}
              />
            </section>

            <section className="alert-section">
              <h3 className="section-title">RESOURCE REQUIREMENT</h3>
              <ResourceRequirementTable
                required={data.resources?.required}
                available={data.resources?.available}
                gapPct={data.resources?.gap_pct || 0}
              />
            </section>

            <section className="alert-section">
              <h3 className="section-title">💰 COST ESTIMATION</h3>
              <div className="grid grid-cols-1 md:grid-cols-3 gap-3 mb-3">
                <div className="rounded-lg border border-slate-200 p-3 bg-slate-50"><div className="text-xs text-slate-500 uppercase">🚛 Transport</div><div className="text-xl font-bold text-[#1a3c5e]">{formatINR(data.cost_breakdown?.transport_cost || 0)}</div></div>
                <div className="rounded-lg border border-slate-200 p-3 bg-slate-50"><div className="text-xs text-slate-500 uppercase">👷 Labor</div><div className="text-xl font-bold text-[#1a3c5e]">{formatINR(data.cost_breakdown?.labor_cost || 0)}</div></div>
                <div className="rounded-lg border border-slate-200 p-3 bg-slate-50"><div className="text-xs text-slate-500 uppercase">🏕 Relief</div><div className="text-xl font-bold text-[#1a3c5e]">{formatINR(data.cost_breakdown?.relief_cost || 0)}</div></div>
              </div>
              <div className="border-t border-slate-200 pt-2">
                <div className="text-xs uppercase text-slate-500 tracking-wide">TOTAL ESTIMATED DEPLOYMENT COST</div>
                <div className="text-3xl font-bold text-[#1a3c5e]">{formatINR(data.cost_breakdown?.total || 0)}</div>
              </div>
            </section>

            <section className="alert-section">
              <h3 className="section-title"><ClipboardList size={16} /> RECOMMENDED ACTIONS</h3>
              <div>
                {(data.recommended_actions || []).slice(0, 5).map((item, idx) => (
                  <div key={idx} className="action-item">
                    <div className="action-number">{idx + 1}</div>
                    <div className="action-text">{item}</div>
                  </div>
                ))}
              </div>
            </section>

            <div className="px-4 pb-6 flex flex-wrap gap-2 justify-end">
              <button className="btn-print" onClick={() => window.print()}>🖨 PRINT REPORT</button>
              <button className="btn-download" onClick={() => downloadHtmlReport(data)}>📥 DOWNLOAD HTML</button>
              <button className="btn-dispatch" onClick={dispatchNow}>🚑 DISPATCH</button>
            </div>
          </div>
        )}
      </div>
    </div>
  );
}
